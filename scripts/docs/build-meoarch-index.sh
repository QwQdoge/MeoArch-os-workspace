#!/usr/bin/env bash
# Regenerates docs/MEOARCH_DOC_INDEX.md: a link to every Markdown document in every MeoArch repository.
# Run from anywhere: bash scripts/docs/build-meoarch-index.sh   (clones expected in ~/projects, override with MEO_PROJECTS)
set -euo pipefail
. "$(dirname "$0")/lib.sh"
OUT="$(cd "$(dirname "$0")/../.." && pwd)/docs/MEOARCH_DOC_INDEX.md"
{
  echo "<!-- generated by scripts/docs/build-meoarch-index.sh; do not edit by hand -->"
  echo "# MeoArch 全部文档索引 / Document Index"
  echo
  echo "> 返回 [MeoArch 主文档](MEOARCH_MASTER.md)。本文件由脚本生成：每个仓库里每一个 Markdown 文档的直达链接（已排除生成物、内置第三方文档与运行时 prompt）。"
  echo
  for r in $MEO_REPOS; do
    d="$MEO_PROJECTS/$r"; [ -d "$d/.git" ] || { echo "skip $r (not cloned)" >&2; continue; }
    br=$(git -C "$d" symbolic-ref --quiet --short refs/remotes/origin/HEAD 2>/dev/null | sed 's#^origin/##' || true)
    [ -n "$br" ] || br=$(git -C "$d" branch --show-current)
    files=$(meo_md_files "$d" index | sort)
    echo "## $r"; echo
    echo "[仓库首页](https://github.com/QwQdoge/$r) · 默认分支 \`$br\` · 本地 \`~/projects/$r\` · $(echo "$files" | grep -c .) 个文档"; echo
    echo "$files" | while IFS= read -r f; do [ -n "$f" ] && echo "- [\`$f\`](https://github.com/QwQdoge/$r/blob/$br/$f)"; done
    echo
  done
} > "$OUT"
echo "wrote $OUT ($(grep -c '^- \[' "$OUT") links)"
